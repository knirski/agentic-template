def test_renderer_purity_under_blocked_ambient_access(
    monkeypatch: pytest.MonkeyPatch,
) -> None:
    def fail(*_args: object, **_kwargs: object) -> object:
        raise AssertionError("ambient access attempted")

    class RaisingMapping(Mapping[str, str]):
        @override
        def __getitem__(self, key: str) -> str:
            raise AssertionError("ambient environment access")

        @override
        def __iter__(self) -> Iterator[str]:
            raise AssertionError("ambient environment access")

        @override
        def __len__(self) -> int:
            raise AssertionError("ambient environment access")

    store, content_ids = fixture_blobs()
    render_input = make_render_input(store, content_ids)
    with monkeypatch.context() as patcher:
        patcher.setattr("builtins.open", fail)
        patcher.setattr(os, "environ", RaisingMapping())
        patcher.setattr(os, "getcwd", fail)
        patcher.setattr(time, "time", fail)
        patcher.setattr(socket, "socket", fail)
        result = render_managed(render_input, store)
    match result:
        case Ok(_):
            pass
        case Err(error):
            raise AssertionError(f"renderer touched ambient state: {error}")


