def test_optional_section_markers_at_line_and_file_boundaries() -> None:
    store, content_ids = fixture_blobs()
    store, eof_id = intern(
        store,
        b"[project]\nname = x\nagentic-template:if:strict:begin\n[tool.ruff]\nstrict = true\nagentic-template:if:strict:end",
    )
    render_input = make_render_input(store, content_ids)
    core = render_input.core.model_copy(
        update={
            "artifacts": (
                render_input.core.artifacts[0].model_copy(
                    update={"template_blob": eof_id}
                ),
                *render_input.core.artifacts[1:],
            )
        }
    )
    rendered = render_bytes(replace(render_input, core=core), store)
    assert rendered["tooling.toml"] == (
        b"[project]\nname = x\n[tool.ruff]\nstrict = true\n"
    )
    store, indented_id = intern(
        store,
        b"[project]\n  agentic-template:if:strict:begin\n[tool.ruff]\nstrict = true\n  agentic-template:if:strict:end\n",
    )
    core = render_input.core.model_copy(
        update={
            "artifacts": (
                render_input.core.artifacts[0].model_copy(
                    update={"template_blob": indented_id}
                ),
                *render_input.core.artifacts[1:],
            )
        }
    )
    rendered = render_bytes(replace(render_input, core=core), store)
    assert rendered["tooling.toml"] == b"[project]\n[tool.ruff]\nstrict = true\n"
    store, inline_id = intern(
        store,
        b"prefix agentic-template:if:strict:begin mid agentic-template:if:strict:end suffix",
    )
    core = render_input.core.model_copy(
        update={
            "artifacts": (
                render_input.core.artifacts[0].model_copy(
                    update={"template_blob": inline_id}
                ),
                *render_input.core.artifacts[1:],
            )
        }
    )
    rendered = render_bytes(replace(render_input, core=core), store)
    assert rendered["tooling.toml"] == b"prefix  mid  suffix\n"
    disabled = MappingProxyType(
        {"semantic-release": {"channel": "next", "strict": False}}
    )
    render_input = make_render_input(store, content_ids, settings=disabled)
    core = render_input.core.model_copy(
        update={
            "artifacts": (
                render_input.core.artifacts[0].model_copy(
                    update={"template_blob": eof_id}
                ),
                *render_input.core.artifacts[1:],
            )
        }
    )
    rendered = render_bytes(replace(render_input, core=core), store)
    assert rendered["tooling.toml"] == b"[project]\nname = x\n"


