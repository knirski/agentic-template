def test_managed_inventory_contains_only_managed_output() -> None:
    store, content_ids = fixture_blobs()
    render_input = make_render_input(store, content_ids)
    match render_managed(render_input, store):
        case Ok(managed):
            inventory = derive_managed_inventory(managed)
        case Err(error):
            raise AssertionError(f"unexpected render failure: {error}")
    assert tuple(entry.path.value for entry in inventory) == (
        ".github/workflows/ci.yml",
        ".releaserc",
        "assets/logo.bin",
        "docs/capabilities.md",
        "pyproject.toml",
        "tooling.toml",
    )
    by_path = {entry.path.value: entry for entry in inventory}
    assert by_path["pyproject.toml"].mode == PosixMode.FILE
    assert by_path["pyproject.toml"].kind == "text"
    assert by_path["pyproject.toml"].sha256 == sha256_hex(EXPECTED_PYPROJECT)
    assert by_path["tooling.toml"].sha256 == sha256_hex(
        b'[project]\nname = "example"\n[tool.ruff]\nstrict = true\n'
    )
    assert by_path["assets/logo.bin"].sha256 == sha256_hex(FIXTURE_TEMPLATES["logo"])


def test_seed_and_legal_bytes_are_digest_addressed_and_never_managed() -> None:
    seed_bytes = b"# README\n"
    legal_bytes = b"Apache-2.0 license text\n"
    store, content_ids = fixture_blobs()
    render_input = make_render_input(store, content_ids)
    render_input = replace(
        render_input,
        licensing=LicensingInfo(
            mode="provided-project-license",
            content_sha256=ContentId.from_bytes(legal_bytes).value,
        ),
        slots=MappingProxyType(
            {
                "readme": SlotContent(
                    mode="file", content_sha256=ContentId.from_bytes(seed_bytes).value
                )
            }
        ),
    )
    match render_managed(render_input, store):
        case Ok(managed):
            rendered_paths = {file.path.value for file in managed}
            inventory = derive_managed_inventory(managed)
        case Err(error):
            raise AssertionError(f"unexpected render failure: {error}")
    assert "README.md" not in rendered_paths
    assert "LICENSE" not in rendered_paths
    assert all(entry.path.value not in {"README.md", "LICENSE"} for entry in inventory)


